// Dual-index lookup supporting both canonical IDs ('b-01') and slug aliases ('benefit_google_ai_plus', 'benefit_nmms_scholarship', etc.)
export const benefitById = (idOrSlug: string): BenefitItem | undefined => {
  if (!idOrSlug) return undefined;
  // Exact match on id or slug
  const direct = mockBenefits.find((b) => b.id === idOrSlug || b.slug === idOrSlug);
  if (direct) return direct;

  // Handle common aliases:
  if (idOrSlug === 'benefit_nmms_scholarship') {
    return mockBenefits.find((b) => b.id === 'b-09');
  }
  if (idOrSlug === 'benefit_sustainability_intern') {
    return mockBenefits.find((b) => b.id === 'b-17');
  }

  // Handle prefix conversions (e.g. 'b-01' <-> 'benefit_01')
  const normalized = idOrSlug.toLowerCase().trim();
  return mockBenefits.find(
    (b) =>
      b.id.toLowerCase() === normalized ||
      (b.slug && b.slug.toLowerCase() === normalized) ||
      b.title.toLowerCase().includes(normalized)
  );
};

